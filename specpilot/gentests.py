"""`sdd gen-tests`: turn a spec's acceptance scenarios into a pytest-playwright regression file.

Spec text is untrusted input. It reaches generated code only through repr(), which always yields
a valid, inert Python string literal, so nothing written in a spec can become executable code.
"""
from __future__ import annotations

from pathlib import Path

from .security import SecurityError, one_line, read_text, safe_join, validate_feature, write_text
from .spec import feature_dir, load_config, parse_scenarios, parse_spec

BEGIN = "# SPECPILOT:GENERATED-BEGIN (rewritten by `sdd gen-tests`; put your own tests below END)"
END = "# SPECPILOT:GENERATED-END"


def _fn(req: str, n: int) -> str:
    return f"test_{req.lower().replace('-', '_')}_{n}"


def render(feature: str, spec: dict, scenarios: list[dict]) -> str:
    by_req: dict = {}
    for s in scenarios:
        by_req.setdefault(s["req"], []).append(s)
    blocks = []
    for req in dict.fromkeys(spec["reqs"]):
        cases = by_req.get(req) or [None]
        for n, sc in enumerate(cases, 1):
            head = f"@pytest.mark.requirement({req!r})\ndef {_fn(req, n)}(page):\n    # {req}\n"
            if sc and sc["given"]:
                body = (f"    run_scenario(\n        page,\n        given={one_line(sc['given'], 300)!r},\n"
                        f"        when={one_line(sc['when'], 300)!r},\n        then={one_line(sc['then'], 300)!r},\n    )\n")
            elif sc:
                body = f"    missing({(req + ': scenario is not in Given/When/Then form: ' + one_line(sc['raw'], 200))!r})\n"
            else:
                body = f"    missing({(req + ': no acceptance scenario in spec.md yet')!r})\n"
            blocks.append(head + body)
    generated = "\n\n".join(blocks) if blocks else "# No requirements found in spec.md yet.\n"
    return f'''"""Regression tests for the "{feature}" feature.

Generated by `sdd gen-tests {feature}` from .sdd/specs/{feature}/spec.md.
Each test is marked with the requirement id it proves, which is how `sdd verify` traces it.
Selectors live in ui_connector.py, not here.
"""
import pytest

from ui_connector import missing, run_scenario  # noqa: F401

{BEGIN}

{generated}
{END}
'''


def gen_tests(root: Path, feature: str) -> dict:
    validate_feature(feature)
    spec_text = read_text(feature_dir(root, feature) / "spec.md")
    if spec_text is None:
        raise SecurityError(f'no spec.md for feature "{feature}" (run: sdd new {feature})')
    spec = parse_spec(spec_text)
    if not spec["reqs"]:
        raise SecurityError(f'spec.md for "{feature}" defines no REQ- requirements yet')
    e2e = safe_join(root, str(load_config(root).get("e2eDir") or "tests/e2e"))
    path = e2e / f"test_{feature.replace('-', '_')}.py"
    fresh = render(feature, spec, parse_scenarios(spec_text))
    previous = read_text(path)
    created = previous is None
    if previous and END in previous:
        fresh = fresh[: fresh.index(END) + len(END)] + previous[previous.index(END) + len(END):]
    write_text(root, path, fresh)
    scenarios = parse_scenarios(spec_text)
    covered = {s["req"] for s in scenarios if s["given"]}
    return {"file": path, "created": created,
            "missing": [r for r in dict.fromkeys(spec["reqs"]) if r not in covered]}
