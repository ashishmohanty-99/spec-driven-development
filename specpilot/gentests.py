"""`sdd gen-tests`: turn a spec's acceptance scenarios into a pytest-playwright regression file.

Spec text is untrusted input. It reaches generated code only through repr(), which always yields
a valid, inert Python string literal, so nothing written in a spec can become executable code.
"""
from __future__ import annotations

from pathlib import Path

from .security import SecurityError, one_line, read_text, validate_feature, write_text
from .spec import ASSETS, PLACEHOLDER, e2e_dir, feature_dir, load_config, parse_scenarios, parse_spec

BEGIN = "# SPECPILOT:GENERATED-BEGIN (rewritten by `sdd gen-tests`; put your own tests below END)"
END = "# SPECPILOT:GENERATED-END"


def _fn(req: str, n: int) -> str:
    return f"test_{req.lower().replace('-', '_')}_{n}"


def usable(scenarios: list[dict]) -> list[dict]:
    """Drop scenarios that are still template placeholders ("Given …, when …, then …")."""
    return [s for s in scenarios if not PLACEHOLDER.search(s["raw"])]


def render(feature: str, spec: dict, scenarios: list[dict]) -> str:
    by_req: dict = {}
    for s in usable(scenarios):
        by_req.setdefault(s["req"], []).append(s)
    blocks = []
    for req in dict.fromkeys(spec["reqs"]):
        cases = by_req.get(req) or [None]
        for n, sc in enumerate(cases, 1):
            head = f"@pytest.mark.requirement({req!r})\ndef {_fn(req, n)}(page):\n    # {req}\n"
            if sc and sc["given"]:
                body = (f"    run_scenario(\n        page,\n        given={_phrase(sc['given'])!r},\n"
                        f"        when={_phrase(sc['when'])!r},\n        then={_phrase(sc['then'])!r},\n    )\n")
            elif sc:
                body = f"    missing({(req + ': scenario is not in Given/When/Then form: ' + _phrase(sc['raw']))!r})\n"
            else:
                body = f"    missing({(req + ': no acceptance scenario in spec.md yet')!r})\n"
            blocks.append(head + body)
    generated = "\n\n".join(blocks) if blocks else "# No requirements found in spec.md yet.\n"
    return f'''"""Regression tests for the "{feature}" feature.

Generated by `sdd gen-tests {feature}` from .sdd/specs/{feature}/spec.md.
Each test is marked with the requirement id it proves, which is how `sdd verify` traces it.
Selectors live in ui_connector.py, not here.
"""
import pytest

from ui_connector import missing, run_scenario  # noqa: F401

{BEGIN}

{generated}
{END}
'''


def _phrase(text: str) -> str:
    """Spec phrase as it may appear in generated code: one line, and never our own marker text."""
    return one_line(text, 300).replace("SPECPILOT:GENERATED", "SPECPILOT-GENERATED")


def _end_of_generated(source: str) -> int:
    """Index just past the END marker line, or -1. The marker only counts at the start of a line."""
    for marker in ("\n" + END + "\n", "\n" + END):
        i = source.find(marker)
        if i >= 0 and (marker.endswith("\n") or i + len(marker) == len(source)):
            return i + 1 + len(END)
    return -1


def ensure_scaffold(root: Path, e2e: Path) -> None:
    """The generated tests import ui_connector; make sure it exists next to them."""
    for name in ("ui_connector.py", "conftest.py"):
        if not (e2e / name).exists():
            write_text(root, e2e / name, (ASSETS / "e2e" / name).read_text(encoding="utf-8"))


def gen_tests(root: Path, feature: str) -> dict:
    validate_feature(feature)
    spec_text = read_text(feature_dir(root, feature) / "spec.md")
    if spec_text is None:
        raise SecurityError(f'no spec.md for feature "{feature}" (run: sdd new {feature})')
    spec = parse_spec(spec_text)
    if not spec["reqs"]:
        raise SecurityError(f'spec.md for "{feature}" defines no REQ- requirements yet')
    e2e = e2e_dir(root)
    path = e2e / f"test_{feature.replace('-', '_')}.py"
    scenarios = usable(parse_scenarios(spec_text))
    fresh = render(feature, spec, scenarios)
    created = not path.exists()
    if not created:
        previous = read_text(path)
        cut = _end_of_generated(previous) if previous else -1
        if cut < 0:
            raise SecurityError(
                f"{path.relative_to(Path(root).resolve())} exists and was not generated by sdd gen-tests. "
                "Refusing to overwrite it: rename it, or move its tests into another file.")
        fresh = fresh[: _end_of_generated(fresh)] + previous[cut:]
    ensure_scaffold(root, e2e)
    write_text(root, path, fresh)
    covered = {s["req"] for s in scenarios if s["given"]}
    return {"file": path, "created": created, "e2eDir": load_config(root)["e2eDir"],
            "missing": [r for r in dict.fromkeys(spec["reqs"]) if r not in covered]}
