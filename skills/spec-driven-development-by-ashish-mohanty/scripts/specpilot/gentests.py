"""`sdd gen-tests`: turn a spec's acceptance scenarios into regression tests for the project's own stack.

Three output forms, chosen by `e2eFramework` in config (detected from the codebase when unset):
  playwright-python  tests/e2e/test_<feature>.py     pytest + pytest-playwright
  playwright-ts      tests/e2e/<feature>.spec.ts     @playwright/test
  gherkin            tests/e2e/<feature>.feature     language-neutral; any Cucumber runner

Spec text is untrusted input. It reaches generated code only as an inert string literal (repr() for
Python, JSON for TypeScript) or, for Gherkin, as a single sanitised line, so nothing written in a
spec can become executable code.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from .security import SecurityError, one_line, read_text, validate_feature, write_text
from .spec import ASSETS, E2E_FRAMEWORKS, e2e_dir, feature_dir, load_config, parse_scenarios, parse_spec

# Narrower than the requirement check: a scenario may legitimately quote markup such as "<b>".
SCENARIO_PLACEHOLDER = re.compile(r"\u2026|\.\.\.|\bTBD\b")
MARK = "SPECPILOT:GENERATED"
NOTE = "(rewritten by `sdd gen-tests`; put your own tests below END)"


def detect_framework(root: Path) -> str:
    """Pick the form that fits the codebase. Anything that is not JS/TS or Python gets Gherkin."""
    profile = json.loads(read_text(Path(root) / ".sdd" / "codebase-profile.json") or "{}")
    langs = [entry.get("name") for entry in profile.get("languages", [])]
    tools = set(profile.get("testTools", [])) | set(profile.get("frameworks", []))
    if "@playwright/test" in tools or "playwright" in tools and "Python" not in langs:
        return "playwright-ts"
    top = langs[0] if langs else None
    if top in ("TypeScript", "JavaScript"):
        return "playwright-ts"
    if top == "Python":
        return "playwright-python"
    return "gherkin"


def framework(root: Path) -> str:
    return load_config(root)["e2eFramework"] or detect_framework(root)


def default_command(fw: str, e2e_rel: str) -> str | None:
    return {"playwright-python": f"pytest {e2e_rel}", "playwright-ts": f"npx playwright test {e2e_rel}"}.get(fw)


def usable(scenarios: list[dict]) -> list[dict]:
    """Drop scenarios that are still template placeholders ("Given …, when …, then …")."""
    return [s for s in scenarios if not SCENARIO_PLACEHOLDER.search(s["raw"])]


def _phrase(text: str) -> str:
    """Spec phrase as it may appear in generated output: one line, and never our own marker text."""
    return one_line(text, 300).replace(MARK, "SPECPILOT-GENERATED")


def _cases(spec: dict, scenarios: list[dict]):
    """Yield (req, n, scenario|None, gap_reason|None) in spec order."""
    by_req: dict = {}
    for s in scenarios:
        by_req.setdefault(s["req"], []).append(s)
    for req in dict.fromkeys(spec["reqs"]):
        for n, sc in enumerate(by_req.get(req) or [None], 1):
            if sc and sc["given"]:
                yield req, n, sc, None
            elif sc:
                yield req, n, None, f"{req}: scenario is not in Given/When/Then form: {_phrase(sc['raw'])}"
            else:
                yield req, n, None, f"{req}: no acceptance scenario in spec.md yet"


# ── playwright-python ────────────────────────────────────────────────────────────────────────

def _render_python(feature: str, spec: dict, scenarios: list[dict]) -> str:
    begin, end = f"# {MARK}-BEGIN {NOTE}", f"# {MARK}-END"
    blocks = []
    for req, n, sc, gap in _cases(spec, scenarios):
        head = f"@pytest.mark.requirement({req!r})\ndef test_{req.lower().replace('-', '_')}_{n}(page):\n    # {req}\n"
        if sc:
            body = (f"    run_scenario(\n        page,\n        given={_phrase(sc['given'])!r},\n"
                    f"        when={_phrase(sc['when'])!r},\n        then={_phrase(sc['then'])!r},\n    )\n")
        else:
            body = f"    missing({gap!r})\n"
        blocks.append(head + body)
    generated = "\n\n".join(blocks)
    return f'''"""Regression tests for the "{feature}" feature.

Generated by `sdd gen-tests {feature}` from .sdd/specs/{feature}/spec.md.
Each test is marked with the requirement id it proves, which is how `sdd verify` traces it.
Selectors live in ui_connector.py, not here.
"""
import pytest

from ui_connector import missing, run_scenario  # noqa: F401

{begin}

{generated}
{end}
'''


# ── playwright-ts ────────────────────────────────────────────────────────────────────────────

def _js(text: str) -> str:
    """A JavaScript string literal. JSON strings are valid JS; `<` is escaped so no markup can form."""
    return json.dumps(text, ensure_ascii=True).replace("<", "\\u003c").replace("/", "\\/")


def _render_ts(feature: str, spec: dict, scenarios: list[dict]) -> str:
    begin, end = f"// {MARK}-BEGIN {NOTE}", f"// {MARK}-END"
    blocks = []
    for req, n, sc, gap in _cases(spec, scenarios):
        if sc:
            title = _js(f"{req} #{n}: {_phrase(sc['raw'])}"[:200])
            blocks.append(
                f"test({title}, async ({{ page }}) => {{\n"
                f"  await runScenario(page, {{\n    given: {_js(_phrase(sc['given']))},\n"
                f"    when: {_js(_phrase(sc['when']))},\n    then: {_js(_phrase(sc['then']))},\n  }});\n}});\n")
        else:
            blocks.append(f"test({_js(f'{req} #{n}')}, async () => {{\n  missing({_js(gap)});\n}});\n")
    generated = "\n".join(blocks)
    return f'''// Regression tests for the "{feature}" feature.
// Generated by `sdd gen-tests {feature}` from .sdd/specs/{feature}/spec.md.
// Each test title starts with the requirement id it proves, which is how `sdd verify` traces it.
// Selectors live in ui-connector.ts, not here.
import {{ test }} from '@playwright/test';
import {{ missing, runScenario }} from './ui-connector';

{begin}

{generated}
{end}
'''


# ── gherkin ──────────────────────────────────────────────────────────────────────────────────

def _render_gherkin(feature: str, spec: dict, scenarios: list[dict]) -> str:
    begin, end = f"# {MARK}-BEGIN {NOTE}", f"# {MARK}-END"
    blocks = []
    for req, n, sc, gap in _cases(spec, scenarios):
        if sc:
            title = one_line(spec["titles"].get(req, ""), 120) or "acceptance"
            blocks.append(f"  @{req}\n  Scenario: {req} #{n} {title}\n    Given {_phrase(sc['given'])}\n"
                          f"    When {_phrase(sc['when'])}\n    Then {_phrase(sc['then'])}\n")
        else:
            blocks.append(f"  # GAP {gap}\n")
    generated = "\n".join(blocks)
    return f'''# Acceptance scenarios for the "{feature}" feature.
# Generated by `sdd gen-tests {feature}` from .sdd/specs/{feature}/spec.md.
# Each scenario is tagged with the requirement id it proves, which is how `sdd verify` traces it.
Feature: {feature}

{begin}

{generated}
{end}
'''


RENDER = {"playwright-python": (_render_python, "test_{snake}.py", "# "),
          "playwright-ts": (_render_ts, "{feature}.spec.ts", "// "),
          "gherkin": (_render_gherkin, "{feature}.feature", "# ")}


def render(feature: str, spec: dict, scenarios: list[dict], fw: str = "playwright-python") -> str:
    return RENDER[fw][0](feature, spec, scenarios)


def _end_of_generated(source: str, comment: str) -> int:
    """Index just past the END marker line, or -1. The marker only counts at the start of a line."""
    end = f"{comment}{MARK}-END"
    i = source.find("\n" + end + "\n")
    if i < 0 and source.endswith("\n" + end):
        i = len(source) - len(end) - 1
    return i + 1 + len(end) if i >= 0 else -1


def ensure_scaffold(root: Path, e2e: Path, fw: str) -> None:
    """Generated tests import the connector; make sure this framework's support files sit next to them."""
    for item in sorted((ASSETS / "e2e" / fw).iterdir()):
        if item.is_file() and not (e2e / item.name).exists():
            write_text(root, e2e / item.name, item.read_text(encoding="utf-8"))


def gen_tests(root: Path, feature: str) -> dict:
    validate_feature(feature)
    spec_text = read_text(feature_dir(root, feature) / "spec.md")
    if spec_text is None:
        raise SecurityError(f'no spec.md for feature "{feature}" (run: sdd new {feature})')
    spec = parse_spec(spec_text)
    if not spec["reqs"]:
        raise SecurityError(f'spec.md for "{feature}" defines no REQ- requirements yet')
    fw = framework(root)
    if fw not in E2E_FRAMEWORKS:
        raise SecurityError(f"unknown e2eFramework {fw!r}")
    renderer, name, comment = RENDER[fw]
    e2e = e2e_dir(root)
    path = e2e / name.format(feature=feature, snake=feature.replace("-", "_"))
    scenarios = usable(parse_scenarios(spec_text))
    fresh = renderer(feature, spec, scenarios)
    created = not path.exists()
    if not created:
        previous = read_text(path)
        cut = _end_of_generated(previous, comment) if previous else -1
        if cut < 0:
            raise SecurityError(
                f"{path.relative_to(Path(root).resolve())} exists and was not generated by sdd gen-tests. "
                "Refusing to overwrite it: rename it, or move its tests into another file.")
        fresh = fresh[: _end_of_generated(fresh, comment)] + previous[cut:]
    ensure_scaffold(root, e2e, fw)
    write_text(root, path, fresh)
    covered = {s["req"] for s in scenarios if s["given"]}
    cfg = load_config(root)
    return {"file": path, "created": created, "e2eDir": cfg["e2eDir"], "framework": fw,
            "command": cfg["commands"].get("e2e") or default_command(fw, cfg["e2eDir"]),
            "missing": [r for r in dict.fromkeys(spec["reqs"]) if r not in covered]}
